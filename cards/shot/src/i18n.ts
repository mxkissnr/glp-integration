export const SUPPORTED_LANGS = ['de', 'en', 'it', 'fr', 'es', 'nl'];

// The active language is per-card state driven by hass.language. It is
// exported through setLang()/getLang() because an ESM import cannot be
// reassigned from the class. English matches the fallback promised above: a
// card that never saw a hass language (a stub, a test) renders in English.
let LANG = 'en';

export function setLang(lang: string): void { LANG = lang; }
export function getLang(): string { return LANG; }

export function T(key: string, ...args: string[]): string {
  // noUncheckedIndexedAccess makes STRINGS.en optional; the en table always exists.
  const v = (STRINGS[LANG] ?? STRINGS.en!)[key] ?? STRINGS.en![key] ?? key;
  return typeof v === 'function' ? v(...args) : v;
}

// Like T(), but for an explicit language instead of the active one. The
// visual card editor's labels are read outside a render, so they must not
// depend on (or change) the card instance's active language.
export function TIn(lang: string, key: string, ...args: string[]): string {
  const v = (STRINGS[lang] ?? STRINGS.en!)[key] ?? STRINGS.en![key] ?? key;
  return typeof v === 'function' ? v(...args) : v;
}
